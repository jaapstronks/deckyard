/**
 * Vendor DOMPurify into client/vendor/ so the browser build loads it from this
 * server instead of a third-party CDN.
 *
 * DOMPurify is already an npm dependency (the server-side sanitizer in
 * shared/sanitize.js imports it), so the version is pinned by package-lock.json
 * with an integrity hash — same reproducibility story as the SHA-pinned Google
 * Fonts, without a second lock file to maintain. This script only copies the
 * already-verified dist file into the tree.
 *
 * Run via `npm run vendor:dompurify` (also part of postinstall).
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const srcDir = path.join(repoRoot, 'node_modules', 'dompurify');
const destDir = path.join(repoRoot, 'client', 'vendor', 'dompurify');

async function main() {
  let version;
  try {
    const pkg = JSON.parse(
      await fs.readFile(path.join(srcDir, 'package.json'), 'utf8')
    );
    version = pkg.version;
  } catch {
    throw new Error(
      'Could not read node_modules/dompurify/package.json. Did npm install run?'
    );
  }

  await fs.mkdir(destDir, { recursive: true });
  // The .map rides along so the minified blob stays byte-identical to the npm
  // dist (sourceMappingURL intact) and devtools stops 404ing on the map.
  const files = [];
  for (const name of ['purify.min.js', 'purify.min.js.map']) {
    const buf = await fs.readFile(path.join(srcDir, 'dist', name));
    await fs.writeFile(path.join(destDir, name), buf);
    files.push({
      path: name,
      sha256: createHash('sha256').update(buf).digest('hex'),
    });
  }

  await fs.writeFile(
    path.join(destDir, 'manifest.json'),
    `${JSON.stringify(
      {
        $comment:
          'Generated by `npm run vendor:dompurify`. The version is whatever package-lock.json resolves; do not hand-edit.',
        source: 'dompurify',
        version,
        files,
      },
      null,
      2
    )}\n`,
    'utf8'
  );

  // eslint-disable-next-line no-console
  console.log(
    `Vendored DOMPurify ${version} to ${path.relative(repoRoot, destDir)}`
  );
}

await main();
