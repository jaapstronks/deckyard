/**
 * Vendor Prism.js and KaTeX into client/vendor/ so the app shell loads them
 * from this server instead of a third-party CDN.
 *
 * Both are npm dependencies pinned by package-lock.json with an integrity
 * hash — same reproducibility story as the SHA-pinned Google Fonts, without a
 * second lock file to maintain. This script copies the already-verified dist
 * files into the tree and records a sha256 per file in the manifest, so the
 * checked-in blobs stay machine-verifiable (tests/vendor-manifests.test.js).
 *
 * What gets vendored follows shared/prism-languages.js: the Prism core plus
 * the base components that replicate the CDN `prism.min.js` bundle, and every
 * component the language map can resolve to. KaTeX ships its js, css and the
 * woff2 fonts the css prefers (modern browsers never fall through to
 * woff/ttf, so those stay out).
 *
 * Run via `npm run vendor:prism-katex` (also part of postinstall).
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import {
  PRISM_BASE_COMPONENTS,
  PRISM_LANGUAGE_COMPONENTS,
} from '../shared/prism-languages.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

async function readVersion(pkgName) {
  try {
    const pkg = JSON.parse(
      await fs.readFile(
        path.join(repoRoot, 'node_modules', pkgName, 'package.json'),
        'utf8'
      )
    );
    return pkg.version;
  } catch {
    throw new Error(
      `Could not read node_modules/${pkgName}/package.json. Did npm install run?`
    );
  }
}

async function copyWithHash(src, destDir, relPath) {
  const dest = path.join(destDir, relPath);
  await fs.mkdir(path.dirname(dest), { recursive: true });
  const buf = await fs.readFile(src);
  await fs.writeFile(dest, buf);
  return {
    path: relPath,
    sha256: createHash('sha256').update(buf).digest('hex'),
  };
}

async function writeManifest(destDir, source, version, files) {
  await fs.writeFile(
    path.join(destDir, 'manifest.json'),
    `${JSON.stringify(
      {
        $comment:
          'Generated by `npm run vendor:prism-katex`. The version is whatever package-lock.json resolves; do not hand-edit.',
        source,
        version,
        files,
      },
      null,
      2
    )}\n`,
    'utf8'
  );
}

async function vendorPrism() {
  const version = await readVersion('prismjs');
  const srcDir = path.join(repoRoot, 'node_modules', 'prismjs');
  const destDir = path.join(repoRoot, 'client', 'vendor', 'prism');
  await fs.rm(destDir, { recursive: true, force: true });

  const components = [
    ...PRISM_BASE_COMPONENTS,
    ...new Set(Object.values(PRISM_LANGUAGE_COMPONENTS).flat()),
  ].filter((c, i, all) => all.indexOf(c) === i);

  const files = [];
  files.push(
    await copyWithHash(
      path.join(srcDir, 'components', 'prism-core.min.js'),
      destDir,
      'components/prism-core.min.js'
    )
  );
  for (const name of components) {
    files.push(
      await copyWithHash(
        path.join(srcDir, 'components', `prism-${name}.min.js`),
        destDir,
        `components/prism-${name}.min.js`
      )
    );
  }
  files.push(
    await copyWithHash(
      path.join(srcDir, 'themes', 'prism-tomorrow.min.css'),
      destDir,
      'themes/prism-tomorrow.min.css'
    )
  );

  await writeManifest(destDir, 'prismjs', version, files);
  return { version, count: files.length };
}

async function vendorKatex() {
  const version = await readVersion('katex');
  const srcDir = path.join(repoRoot, 'node_modules', 'katex', 'dist');
  const destDir = path.join(repoRoot, 'client', 'vendor', 'katex');
  await fs.rm(destDir, { recursive: true, force: true });

  const files = [];
  for (const name of ['katex.min.js', 'katex.min.css']) {
    files.push(await copyWithHash(path.join(srcDir, name), destDir, name));
  }
  const fonts = (await fs.readdir(path.join(srcDir, 'fonts')))
    .filter((f) => f.endsWith('.woff2'))
    .sort();
  for (const font of fonts) {
    files.push(
      await copyWithHash(
        path.join(srcDir, 'fonts', font),
        destDir,
        `fonts/${font}`
      )
    );
  }

  await writeManifest(destDir, 'katex', version, files);
  return { version, count: files.length };
}

async function main() {
  const prism = await vendorPrism();
  const katex = await vendorKatex();
  // eslint-disable-next-line no-console
  console.log(
    `Vendored Prism ${prism.version} (${prism.count} files) and KaTeX ${katex.version} (${katex.count} files) to client/vendor/`
  );
}

await main();
