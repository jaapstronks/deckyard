/**
 * GDPR Data Access Functions for View Sessions
 *
 * Handles GDPR compliance operations:
 * - Data export (right to access)
 * - Data deletion (right to erasure)
 * - Data anonymization (retention policy)
 *
 * **The data subject is the scope; the organization plays no part.** These
 * functions act on one email address across the whole instance. A person is
 * one person on this deployment — `user_settings` holds one row per person
 * instance-wide, not one per organization (tenant-isolation.md rule R3) — and the operator
 * of the instance is the single controller answering the request, so an
 * erasure that stopped at an organization boundary would silently under-delete and
 * still report success. That is exactly what the earlier organization filter
 * did (#627): it matched `view_sessions.organization_id`, a column the viewer's
 * own browser filled in, against the authenticated caller's organization. The
 * column is gone (migration 065) and the filter with it.
 *
 * **A device id is never accepted from a caller.** The value is generated by
 * the viewer's own browser and travels in the request body, so producing one
 * proves nothing about whose device it is. Accepting it as an identifier would
 * let anybody export — or erase — the cross-deck viewing history of a device
 * whose id they guessed or obtained. (Obtaining one used to be trivial: the
 * session-list endpoint handed every reader of a deck the raw 32-hex id. It now
 * returns a per-deck HMAC label instead — `publicDeviceLabel` in
 * `server/analytics/helpers.js` — which narrows the exposure but does not change
 * the rule.) The email erasure above therefore takes an email and nothing else.
 *
 * `eraseAnalyticsDataForDevice` below *does* erase by device id — instance-wide,
 * the same cascade as the email path — but the device id reaches it **only
 * server-side**, resolved by the anonymous-erase route
 * (`POST /api/track/my-data/erase`) from a live `session_token` the caller
 * proved possession of. That token *is* the proof this module otherwise lacks:
 * holding it means the browser that opened the session is asking to be
 * forgotten. The device id is still never read from client input — the route
 * looks it up from the possessed token and hands it here.
 */

import { withDbGuard } from '../utils/db-guard.js';

/**
 * Export all analytics data for one person (GDPR right of access).
 * Matches on email address across the whole instance; see the module header.
 * @param {Object} identifier - User identifier
 * @param {string} identifier.email - The data subject's email address
 * @returns {Promise<{ok: boolean, data?: Object, reason?: string}>}
 */
export async function exportUserAnalyticsData({ email }) {
  const normalizedEmail = email?.toLowerCase()?.trim();

  if (!normalizedEmail) {
    return { ok: false, reason: 'No identifier provided' };
  }

  return withDbGuard({ ok: false, reason: 'unavailable' }, async (db) => {
    const sessions = await db
      .selectFrom('view_sessions')
      .selectAll()
      .where('viewer_email', '=', normalizedEmail)
      .orderBy('started_at', 'desc')
      .execute();

    if (sessions.length === 0) {
      return { ok: true, data: { sessions: [], slideViews: [] } };
    }

    // Get session IDs for slide view lookup
    const sessionIds = sessions.map((s) => s.id);

    // Get slide views for these sessions
    const slideViews = await db
      .selectFrom('slide_views')
      .selectAll()
      .where('view_session_id', 'in', sessionIds)
      .orderBy('entered_at', 'desc')
      .execute();

    // Format data for export (remove internal IDs, tokens). The raw device id
    // stays raw here on purpose: this is the data subject's own export, so
    // there is nobody to correlate them with — unlike the deck-reader-facing
    // session list, which gets a per-deck label instead.
    const exportedSessions = sessions.map((row) => ({
      presentationId: row.presentation_id,
      sourceType: row.source_type,
      viewerType: row.viewer_type,
      viewerEmail: row.viewer_email,
      deviceId: row.device_id,
      startedAt: row.started_at,
      endedAt: row.ended_at,
      durationSeconds: row.duration_seconds,
      exitSlideIndex: row.exit_slide_index,
      ipAddress: row.ip_address,
      userAgent: row.user_agent,
      createdAt: row.created_at,
    }));

    const exportedSlideViews = slideViews.map((row) => ({
      presentationId: row.presentation_id,
      slideId: row.slide_id,
      slideIndex: row.slide_index,
      enteredAt: row.entered_at,
      exitedAt: row.exited_at,
      durationSeconds: row.duration_seconds,
      visitNumber: row.visit_number,
    }));

    return {
      ok: true,
      data: {
        exportedAt: new Date().toISOString(),
        identifier: { email: normalizedEmail },
        sessions: exportedSessions,
        slideViews: exportedSlideViews,
        totalSessions: exportedSessions.length,
        totalSlideViews: exportedSlideViews.length,
      },
    };
  });
}

/**
 * Delete all analytics data for one person (GDPR right to erasure).
 * Matches on email address across the whole instance; see the module header.
 * @param {Object} identifier - User identifier
 * @param {string} identifier.email - The data subject's email address
 * @returns {Promise<{ok: boolean, deleted?: {sessions: number, slideViews: number}, reason?: string}>}
 */
export async function deleteUserAnalyticsData({ email }) {
  const normalizedEmail = email?.toLowerCase()?.trim();

  if (!normalizedEmail) {
    return { ok: false, reason: 'No identifier provided' };
  }

  return withDbGuard({ ok: false, reason: 'unavailable' }, async (db) =>
    db.transaction().execute(async (trx) => {
      const sessions = await trx
        .selectFrom('view_sessions')
        .select('id')
        .where('viewer_email', '=', normalizedEmail)
        .execute();
      return eraseSessionRows(
        trx,
        sessions.map((s) => s.id),
      );
    }),
  );
}

/**
 * Erase all analytics data for one device, instance-wide — the anonymous
 * viewer's "forget me". Deletes every `view_sessions` row carrying this device
 * id and their `slide_views`, in one transaction, and reports how many.
 *
 * **The device id arrives server-side only**, resolved from a session token the
 * caller proved possession of (`POST /api/track/my-data/erase`); it is never
 * read from client input — see the module header on why a client-supplied
 * device id cannot authorize anything. Identity is the scope, matching the email
 * erasure: a wipe that stopped at the deck the viewer happens to be looking at
 * would report success while leaving that same device's history on every other
 * deck.
 *
 * @param {Object} identifier
 * @param {string} identifier.deviceId - The device id, resolved server-side.
 * @returns {Promise<{ok: boolean, deleted?: {sessions: number, slideViews: number}, reason?: string}>}
 */
export async function eraseAnalyticsDataForDevice({ deviceId } = {}) {
  const id = typeof deviceId === 'string' ? deviceId.trim() : '';
  if (!id) {
    return { ok: false, reason: 'No device id provided' };
  }

  return withDbGuard({ ok: false, reason: 'unavailable' }, async (db) =>
    db.transaction().execute(async (trx) => {
      const sessions = await trx
        .selectFrom('view_sessions')
        .select('id')
        .where('device_id', '=', id)
        .execute();
      return eraseSessionRows(
        trx,
        sessions.map((s) => s.id),
      );
    }),
  );
}

/**
 * Erase a single analytics session and its slide views — the fallback for the
 * anonymous-erase route when the possessed session carries no device id, so
 * there is nothing to cascade across. Same transaction and shape as the wider
 * erasures; only the scope is narrower.
 *
 * @param {Object} identifier
 * @param {string} identifier.sessionId - The `view_sessions.id` to erase.
 * @returns {Promise<{ok: boolean, deleted?: {sessions: number, slideViews: number}, reason?: string}>}
 */
export async function eraseAnalyticsDataForSession({ sessionId } = {}) {
  const id = typeof sessionId === 'string' ? sessionId.trim() : '';
  if (!id) {
    return { ok: false, reason: 'No session id provided' };
  }

  return withDbGuard({ ok: false, reason: 'unavailable' }, async (db) =>
    db.transaction().execute(async (trx) => eraseSessionRows(trx, [id])),
  );
}

/**
 * Delete the given view sessions and their slide views inside a transaction,
 * slide views first for the foreign key. The one erase primitive the three
 * right-to-erasure paths (email, device, single session) share, so they hard
 * delete identically and report the same `{sessions, slideViews}` shape.
 *
 * @param {Object} trx - Kysely transaction handle.
 * @param {string[]} sessionIds - The `view_sessions.id` values to erase.
 * @returns {Promise<{ok: boolean, deleted: {sessions: number, slideViews: number}}>}
 */
async function eraseSessionRows(trx, sessionIds) {
  let deletedSlideViews = 0;
  let deletedSessions = 0;

  if (sessionIds.length > 0) {
    // Delete slide views first (foreign key constraint).
    const slideViewResult = await trx
      .deleteFrom('slide_views')
      .where('view_session_id', 'in', sessionIds)
      .executeTakeFirst();
    deletedSlideViews = Number(slideViewResult.numDeletedRows) || 0;

    const sessionResult = await trx
      .deleteFrom('view_sessions')
      .where('id', 'in', sessionIds)
      .executeTakeFirst();
    deletedSessions = Number(sessionResult.numDeletedRows) || 0;
  }

  return {
    ok: true,
    deleted: { sessions: deletedSessions, slideViews: deletedSlideViews },
  };
}

/**
 * Anonymize IP addresses for old sessions.
 * Replaces IP addresses with hashed versions after retention period.
 * @param {string} olderThan - ISO date string
 * @returns {Promise<{anonymized: number}>}
 */
export async function anonymizeOldIpAddresses(olderThan) {
  return withDbGuard({ anonymized: 0 }, async (db) => {
    // Update sessions older than threshold to have anonymized IPs
    // We set them to null since hashing would still be linkable
    const result = await db
      .updateTable('view_sessions')
      .set({ ip_address: null })
      .where('created_at', '<', olderThan)
      .where('ip_address', 'is not', null)
      .executeTakeFirst();

    return { anonymized: Number(result.numUpdatedRows) || 0 };
  });
}
